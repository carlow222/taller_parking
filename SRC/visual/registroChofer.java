    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {                                         
        String nombre = jTextField2.getText().trim();
        String apellido = jTextField1.getText().trim();
        String cedula = jTextField3.getText().trim();
        
        if (nombre.isEmpty() || apellido.isEmpty() || cedula.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Debe completar todos los campos de texto.", "Error de Validación", JOptionPane.ERROR_MESSAGE);
            return; 
        }
        
        String tieneLicencia = jRadioButton2.isSelected() ? "Sí" : "No";
        String licenciasSeleccionadas = "";
        
        if (jRadioButton2.isSelected()) {
            if (jCheckBox1.isSelected()) licenciasSeleccionadas += "A2 ";
            if (jCheckBox2.isSelected()) licenciasSeleccionadas += "B1 ";
            if (jCheckBox3.isSelected()) licenciasSeleccionadas += "B2 ";
            if (jCheckBox4.isSelected()) licenciasSeleccionadas += "B3 ";
            if (jCheckBox5.isSelected()) licenciasSeleccionadas += "C1 ";
            if (jCheckBox6.isSelected()) licenciasSeleccionadas += "C2 ";
            
            if (licenciasSeleccionadas.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Seleccione al menos un tipo de licencia.", "Atención", JOptionPane.WARNING_MESSAGE);
                return;
            }
        } else {
            licenciasSeleccionadas = "Ninguna";
        }
        
        try {
            String licenciaFinal = tieneLicencia.equals("Sí") ? "LIC-" + licenciasSeleccionadas.trim() : "LIC-Ninguna";
            modelo.chofer_modelo obj_chofer = new modelo.chofer_modelo(nombre + " " + apellido, cedula, licenciaFinal);
            controlador.controlador_maestro maestro = controlador.controlador_maestro.getInstancia();
            maestro.getApi().agregarChofer(obj_chofer);
            
            String mensaje = "Registro Exitoso:\nNombre: " + nombre + " " + apellido + "\nCédula: " + cedula + "\nLicencia: " + tieneLicencia + " (" + licenciasSeleccionadas.trim() + ")";
            JOptionPane.showMessageDialog(this, mensaje, "Sistema", JOptionPane.INFORMATION_MESSAGE);
            this.dispose();
        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al guardar el chofer.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }                                        

