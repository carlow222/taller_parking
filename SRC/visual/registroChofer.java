    private void cambiarEstadoCasillas(boolean estado) {
        javax.swing.JCheckBox[] casillas = {
            jCheckBox1, jCheckBox2, jCheckBox3, 
            jCheckBox4, jCheckBox5, jCheckBox6
        };
        for (javax.swing.JCheckBox casilla : casillas) {
            casilla.setEnabled(estado);
            if (!estado) casilla.setSelected(false);
        }
    }

